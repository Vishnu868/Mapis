"""Builds every figure and every number used in mapis_final_slides.tex.
Inputs: data/benchmark_seed42.json (results\\benchmark.json of the seed-42 run), data/history_*.json (training logs),
and the 3-seed / sweep / live-agent numbers copied from results\\seeds\\summary.json, stateless_sweep*.json, live_agentdojo.json.
Run: python make_report.py   (needs matplotlib)"""
import json, pathlib
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

D = pathlib.Path("data"); F = pathlib.Path("figures"); F.mkdir(exist_ok=True)
bench = json.load(open(D / "benchmark_seed42.json"))
hs = json.load(open(D / "history_stateful.json")); hl = json.load(open(D / "history_stateless.json"))
MAROON, GREY = "#A4123F", "#8A949C"

def m(o):
    tp, fn, fp, tn = o["tp"], o["fn"], o["fp"], o["tn"]
    n = tp + fn + fp + tn; p = tp / (tp + fp) if tp + fp else 0; r = tp / (tp + fn)
    f = 2 * p * r / (p + r) if p + r else 0
    return dict(acc=100 * (tp + tn) / n, prec=100 * p, rec=100 * r, f1=100 * f, fpr=100 * fp / (fp + tn), tp=tp, fn=fn, fp=fp, tn=tn)

# seed-42 session-level counts (tp, fn, fp, tn) from results\benchmark*.json
pub = {"llamaguard": (1106, 179, 920, 99), "promptguard": (97, 1188, 1, 1018), "protectai": (685, 600, 504, 515)}
sysm = {k: m(bench[k]["overall"]) for k in ("mapis", "mapis-model", "mapis-no-provenance", "deberta-v3-small", "regex")}
for k, (tp, fn, fp, tn) in pub.items():
    sysm[k] = m(dict(tp=tp, fn=fn, fp=fp, tn=tn))

names = {"regex": "Regex", "promptguard": "PG", "protectai": "PAI", "llamaguard": "LG", "deberta-v3-small": "SL", "mapis": "MAP", "mapis-model": "MOD"}
lines = ["% generated by make_report.py -- do not edit"]
def mac(name, val): lines.append("\\newcommand{\\%s}{%s}" % (name, val))
for k, tag in names.items():
    s = sysm[k]
    for f, key in (("Acc", "acc"), ("Prec", "prec"), ("Rec", "rec"), ("F", "f1"), ("Fpr", "fpr")):
        mac(f"N{tag}{f}", f"{s[key]:.1f}")
    for key in ("tp", "fn", "fp", "tn"):
        mac(f"N{tag}{key.upper()}", f"{s[key]:,}")
# training logs
mac("NLossStateful", f"{hs[1]['train_loss']:.4f}"); mac("NLossStateless", f"{hl[1]['train_loss']:.4f}")
mac("NLossStatefulOne", f"{hs[0]['train_loss']:.4f}"); mac("NLossStatelessOne", f"{hl[0]['train_loss']:.4f}")
for tag, h in (("Stateful", hs), ("Stateless", hl)):
    v = h[1]["validation"]
    mac(f"NVal{tag}F", f"{v['f1']:.4f}"); mac(f"NVal{tag}Acc", f"{v['accuracy']:.4f}"); mac(f"NVal{tag}Fpr", f"{v['fpr']:.4f}")
    mac(f"NVal{tag}Prec", f"{v['precision']:.4f}"); mac(f"NVal{tag}Rec", f"{v['recall']:.4f}")
open(F / "numbers.tex", "w").write("\n".join(lines) + "\n")

# ---------------- figures
plt.rcParams.update({"font.size": 11, "axes.spines.top": False, "axes.spines.right": False})
# 1. training curves
fig, ax = plt.subplots(1, 2, figsize=(9, 3.4))
ep = [1, 2]
ax[0].plot(ep, [h["train_loss"] for h in hs], "o-", color=MAROON, label="MAPIS (stateful)")
ax[0].plot(ep, [h["train_loss"] for h in hl], "o-", color=GREY, label="Baseline (stateless)")
ax[0].set_xlabel("Epoch"); ax[0].set_ylabel("Training loss"); ax[0].set_xticks(ep); ax[0].grid(alpha=.3); ax[0].legend(frameon=False)
ax[0].set_title("Training loss")
ax[1].plot(ep, [h["validation"]["f1"] for h in hs], "o-", color=MAROON, label="MAPIS (stateful)")
ax[1].plot(ep, [h["validation"]["f1"] for h in hl], "o-", color=GREY, label="Baseline (stateless)")
ax[1].set_xlabel("Epoch"); ax[1].set_ylabel("Validation F1"); ax[1].set_xticks(ep); ax[1].grid(alpha=.3); ax[1].set_ylim(0.8, 1.0)
ax[1].set_title("Validation F1 (9,064 events)")
fig.tight_layout(); fig.savefig(F / "train_curves.png", dpi=200); plt.close(fig)

# 2. confusion matrices
fig, ax = plt.subplots(1, 2, figsize=(7.2, 3.2))
for a, k, t in zip(ax, ("deberta-v3-small", "mapis"), ("Baseline: stateless DeBERTa", "MAPIS")):
    s = sysm[k]; M = [[s["tp"], s["fn"]], [s["fp"], s["tn"]]]
    a.imshow([[1, 0], [0, 1]], cmap="Greens", alpha=.35, vmin=0, vmax=1.6)
    a.imshow([[0, 1], [1, 0]], cmap="Reds", alpha=.25, vmin=0, vmax=1.6)
    for i in range(2):
        for j in range(2):
            a.text(j, i, f"{M[i][j]:,}", ha="center", va="center", fontsize=14, fontweight="bold" if i == j else "normal")
    a.set_xticks([0, 1]); a.set_xticklabels(["pred. attack", "pred. safe"]); a.set_yticks([0, 1]); a.set_yticklabels(["attack", "safe"])
    a.set_title(t); [sp.set_visible(False) for sp in a.spines.values()]
fig.tight_layout(); fig.savefig(F / "confusion.png", dpi=200); plt.close(fig)

# 3. headline bar chart (3-seed means for MAPIS and stateless; others seed-independent)
rows = [("MAPIS", 97.7, 0.5), ("Stateless\nDeBERTa", 94.6, 35.2), ("Llama\nGuard 3", 86.1, 90.3), ("ProtectAI", 53.3, 49.5), ("Prompt\nGuard 2", 7.5, 0.1)]
fig, a = plt.subplots(figsize=(8, 3.3)); x = range(len(rows)); w = .38
a.bar([i - w / 2 for i in x], [r[1] for r in rows], w, color=MAROON, label="Recall (%)")
a.bar([i + w / 2 for i in x], [r[2] for r in rows], w, color=GREY, label="False-positive rate (%)")
for i, r in enumerate(rows):
    a.text(i - w / 2, r[1] + 1, f"{r[1]}", ha="center", fontsize=9); a.text(i + w / 2, r[2] + 1, f"{r[2]}", ha="center", fontsize=9)
a.set_xticks(list(x)); a.set_xticklabels([r[0] for r in rows]); a.set_ylim(0, 108); a.legend(frameon=False, ncol=2, loc="upper right")
a.set_title("2,304 held-out sessions"); fig.tight_layout(); fig.savefig(F / "results_bar.png", dpi=200); plt.close(fig)

# 4. matched-FPR chart
fig, a = plt.subplots(figsize=(5.2, 3.2))
cats = ["Multi-hop", "Adaptive"]; mp = [100, 100]; sl = [4.3, 6.1]
a.bar([0 - .2, 1 - .2], mp, .38, color=MAROON, label="MAPIS"); a.bar([0 + .2, 1 + .2], sl, .38, color=GREY, label="Stateless, FPR $\\leq$ 5%")
for i in range(2):
    a.text(i - .2, mp[i] + 1.5, str(mp[i]), ha="center"); a.text(i + .2, sl[i] + 1.5, str(sl[i]), ha="center")
a.set_xticks([0, 1]); a.set_xticklabels(cats); a.set_ylabel("Recall (%)"); a.set_ylim(0, 135); a.legend(frameon=False, loc="upper right", fontsize=9)
fig.tight_layout(); fig.savefig(F / "matched_fpr.png", dpi=200); plt.close(fig)
print("ok", {k: round(v["rec"], 1) for k, v in sysm.items()})
